def year_hint(date: str) -> str:
    """보도일 'YYYY-MM-DD' → '[연도 기준] 올해=2025년, 지난해(작년)=2024년, 내년=2026년'.

    모델이 상대 날짜를 직접 계산하다 틀리는 문제(실험 3)를 코드 계산으로 대신한다. 연도가 없으면 빈 문자열.
    """
    if len(date) < 4 or not date[:4].isdigit():
        return ""
    y = int(date[:4])
    return f"[연도 기준] 올해={y}년, 지난해(작년)={y - 1}년, 내년={y + 1}년"


def format_context(sources, date_hints: bool = False) -> str:
    """검색 결과(Source 목록)를 프롬프트의 [참고 문서] 블록으로 만든다.

    각 문서 머리줄에 번호·출처 종류·발행처·보도일·제목을 넣어, 모델이
    [n] 표기와 출처 종류 명시(규칙 4, 5), 보도일 구분(규칙 8)을 할 수 있게 한다.
    date_hints=True(프롬프트 v3)이면 보도일로 계산한 [연도 기준]도 붙인다.
    """
    blocks = []
    for s in sources:
        head = f"[{s.n}] {s.type_label} | 발행처: {s.source} | 보도일: {s.date} | 제목: {s.title}"
        if date_hints and year_hint(s.date):
            head += f" | {year_hint(s.date)}"
        if s.section:
            head += f" | 섹션: {s.section}"
        if s.page:
            head += f" | {s.page}쪽"
        blocks.append(f"{head}\n{s.text.strip()}")
    return "\n\n".join(blocks)
