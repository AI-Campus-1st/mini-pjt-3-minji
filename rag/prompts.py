def format_context(sources) -> str:
    """검색 결과(Source 목록)를 프롬프트의 [참고 문서] 블록으로 만든다.

    각 문서 머리줄에 번호·출처 종류·발행처·보도일·제목을 넣어, 모델이
    [n] 표기와 출처 종류 명시(규칙 4, 5), 보도일 구분(규칙 8)을 할 수 있게 한다.
    """
    blocks = []
    for s in sources:
        head = f"[{s.n}] {s.type_label} | 발행처: {s.source} | 보도일: {s.date} | 제목: {s.title}"
        if s.section:
            head += f" | 섹션: {s.section}"
        if s.page:
            head += f" | {s.page}쪽"
        blocks.append(f"{head}\n{s.text.strip()}")
    return "\n\n".join(blocks)
