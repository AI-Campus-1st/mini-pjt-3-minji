REFUSAL = "제공된 자료에서 확인할 수 없습니다."



def is_refusal(answer: str) -> bool:
    """답변이 거절인지 판정한다 (Day 5 거절 정확도 채점, 화면 출처 라벨에 사용).

    모델이 거절 문구를 조금 바꿔 쓰는 경우("제공된 자료에서 ○○은 확인할 수 없습니다")도
    거절로 인정하기 위해, 첫 문장에 '제공된 자료'와 '확인할 수 없'이 함께 있으면 거절로 본다.
    """
    first = answer.strip().split("\n", 1)[0].split(". ", 1)[0]
    return answer.strip().startswith(REFUSAL) or ("제공된 자료" in first and "확인할 수 없" in first)


